import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import accuracy_score

raw_mail_data=pd.read_csv('/content/mail_data.csv')

print(raw_mail_data)

# Replace null values with an empty string
mail_data = raw_mail_data.where(pd.notnull(raw_mail_data), '')

mail_data.head()

mail_data.shape

# Label spam mail as 0 and ham mail as 1

mail_data.loc[mail_data['Category'] == 'spam', 'Category'] = 0

mail_data.loc[mail_data['Category'] == 'ham', 'Category'] = 1

mail_data['Category'].value_counts()

X=mail_data['Message']
Y=mail_data['Category']

print(X,Y)

X_train, X_test, Y_train, Y_test = train_test_split(
    X, Y, test_size=0.2, random_state=3
)

print(mail_data.shape, X_train.shape, X_test.shape)

#feature extraction
feature_extraction = TfidfVectorizer(
    min_df=1,
    stop_words='english',
    lowercase=True
)

X_train_features = feature_extraction.fit_transform(X_train)
X_test_features = feature_extraction.transform(X_test)

#converting values of Y in integers
Y_test=Y_test.astype('int')
Y_train=Y_train.astype('int')

print(X_train_features)

# training the Logistic Regression model with the training data
model=LogisticRegression()

model.fit(X_train_features,Y_train)

"""Training data evaluation

"""

predicting_X_train=model.predict(X_train_features)
Accuracy_score_of_X_train=accuracy_score(Y_train,predicting_X_train)

print('Accuracy on training data:',Accuracy_score_of_X_train)

"""Testing data evaluation

"""

predicting_X_test=model.predict(X_test_features)
Accuracy_score_of_X_test=accuracy_score(Y_test,predicting_X_test)

print('Accuracy on training data:',Accuracy_score_of_X_test)

"""A PREDICTIVE SYSTEM"""

input = ["I've been searching for the right words to thank you for this breather. I promise i wont take your help for granted and will fulfil my promise. You have been wonderful and a blessing at all times"]

# convert text to feature vectors
input_data_features = feature_extraction.transform(input)

# making prediction

prediction = model.predict(input_data_features)
print(prediction)


if (prediction[0]==1):
  print('Ham mail')

else:
  print('Spam mail')

